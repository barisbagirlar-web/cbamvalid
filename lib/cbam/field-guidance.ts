export type FieldGuidancePath = (typeof FIELD_GUIDANCE)[number]["fieldPath"];

export function getFieldGuidance(fieldPath: string): FieldGuidanceRecord | undefined {
  return FIELD_GUIDANCE.find((record) => record.fieldPath === fieldPath);
}

/**
 * Resolve a guidance record for a concrete instance path such as "goods.0.cnCode"
 * by stripping the array index (goods.0.cnCode → goods.*.cnCode).
 */
export function getFieldGuidanceForPath(instancePath: string): FieldGuidanceRecord | undefined {
  const normalized = instancePath
    .split(".")
    .map((segment) => (/^\d+$/.test(segment) ? "*" : segment))
    .join(".");
  return getFieldGuidance(normalized);
}

export const FIELD_GUIDANCE_BY_PATH: ReadonlyMap<string, FieldGuidanceRecord> = new Map(
  FIELD_GUIDANCE.map((record) => [record.fieldPath, record])
);
