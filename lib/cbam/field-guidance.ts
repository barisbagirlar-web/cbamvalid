/**
 * FAZ P0 — Field-based guidance registry.
 *
 * Every material field carries a full guidance record telling the operator
 * why the field is required, what format to use, which documents are accepted,
 * who should issue them, the period they must cover and how a gap affects the
 * report. Guidance records are also the source for the wizard link options and
 * the step validation registry (see wizard-validation.ts).
 */

