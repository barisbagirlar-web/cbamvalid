export const SEO_ROUTE_REGISTRY: readonly SeoRouteContract[] = [...STATIC_ROUTES, ...CN_DETAIL_ROUTES];

const BY_PATH = new Map(SEO_ROUTE_REGISTRY.map((route) => [route.path, route]));

export function getSeoRoute(path: string): SeoRouteContract | undefined {
  return BY_PATH.get(path);
}

export function requireSeoRoute(path: string): SeoRouteContract {
  const route = getSeoRoute(path);
  if (!route) {
    throw new Error(`SEO registry missing route: ${path}`);
  }
  return route;
}

export function listIndexableSeoRoutes(): readonly SeoRouteContract[] {
  return SEO_ROUTE_REGISTRY.filter((route) => route.indexability === "index");
}

export function listSitemapRoutes(): readonly SeoRouteContract[] {
  return SEO_ROUTE_REGISTRY.filter(
    (route) => route.indexability === "index" && route.sitemapEligible,
  );
}

/** @deprecated Legacy export name — prefer SEO_ROUTE_REGISTRY / getSeoRoute. */
export const seoRegistry: Record<string, SeoRouteContract> = Object.fromEntries(
  SEO_ROUTE_REGISTRY.map((route) => [route.path, route]),
);
